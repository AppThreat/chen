if want clangcl-windows-x64; then clangcl_table clangcl-windows-x64 x86_64-pc-windows-msvc; fi
if want clangcl-windows-arm64; then clangcl_table clangcl-windows-arm64 aarch64-pc-windows-msvc; fi
