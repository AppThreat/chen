#!/bin/sh
# Generates the predefined macro tables c2cpg falls back to when a translation unit's compiler
# cannot be run (src/main/resources/predefined-macros/*.txt).
#
# Each table lists the macros a real compiler predefines for one target, for C and for C++, in
# the format of the EDG C/C++ front end's predefined_macros.txt (see its make_predef_macro_table):
#
#   mode[,mode]   cannot_redefine   name   value
#
# where the modes are gnu/gcc/gpp for GCC (both languages/C/C++), clang/clang_c/clang_cpp for
# Clang, and microsoft/microsoft_c/microsoft_cpp for MSVC. Tables for other toolchains use their
# own modes (tinycc, iar, ti_arm, ti_msp430) or the modes of the compiler they embed (emscripten
# and the Intel LLVM compilers are clang; nvcc's own macros carry the all mode, since the table is
# merged over the host compiler's).
#
# GCC runs in Docker (the official gcc image, one run per platform). Clang is the LLVM clang on
# the PATH (or $CLANG), asked for each target with --target. The MSVC tables are what clang
# predefines in MSVC compatibility mode (as clang-cl does), without clang's own identity macros:
# MSVC's cl.exe has no option that lists its predefined macros. The clang-cl tables keep clang's
# identity, since clang --driver-mode=cl predefines it.
#
# The other toolchains run in Docker where an image can install them (tcc and the bare-metal GCC
# cross compiler from Debian, Emscripten from the emsdk image, nvcc from the CUDA image), and
# where none can, their documented macros are written with the source named in the header.
#
# Usage: tools/predefined-macros/generate.sh [output-dir] [table ...]
#
# Without table names every table is regenerated. Naming tables regenerates only those, so the
# tables of compilers whose generators ran with other tool versions keep their bytes.

set -eu

OUT=${1:-"$(cd "$(dirname "$0")/../.." && pwd)/src/main/resources/predefined-macros"}
shift $(($# > 0))
CLANG=${CLANG:-clang}
GCC_IMAGE=${GCC_IMAGE:-gcc:14}
MSVC_VERSION=${MSVC_VERSION:-19.40}
DEBIAN_IMAGE=${DEBIAN_IMAGE:-debian:bookworm-slim}
EMSDK_IMAGE=${EMSDK_IMAGE:-emscripten/emsdk:3.1.64}
CUDA_IMAGE=${CUDA_IMAGE:-nvidia/cuda:12.4.1-devel-ubuntu22.04}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

# merge <c-macros> <cpp-macros> <both-mode> <c-mode> <cpp-mode>: one table body on stdout
merge() {
  awk -v both="$3" -v cmode="$4" -v cppmode="$5" '
    function parse(line,   rest, name, value, i) {
      rest = substr(line, 9)
      if (match(rest, /^[A-Za-z_][A-Za-z0-9_]*\([^)]*\)/)) { name = substr(rest, 1, RLENGTH) }
      else { match(rest, /^[A-Za-z_][A-Za-z0-9_]*/); name = substr(rest, 1, RLENGTH) }
      value = substr(rest, length(name) + 1); sub(/^ /, "", value)
      PNAME = name; PVALUE = value
    }
    FNR == NR { if ($0 ~ /^#define /) { parse($0); c[PNAME] = PVALUE } ; next }
    { if ($0 ~ /^#define /) { parse($0); cpp[PNAME] = PVALUE } }
    END {
      for (n in c) {
        if ((n in cpp) && cpp[n] == c[n]) print both " no  " n " " c[n]
        else print cmode " no  " n " " c[n]
      }
      for (n in cpp) if (!(n in c) || cpp[n] != c[n]) print cppmode " no  " n " " cpp[n]
    }' "$1" "$2" | LC_ALL=C sort -k3,3 -k1,1
}

# header <file> <description> <c-command> <cpp-command> <version text>
header() {
  {
    echo "# Predefined macros of $2."
    echo "#"
    echo "# Format (as the EDG C/C++ front end's predefined_macros.txt):"
    echo "#   mode[,mode]   cannot_redefine   name   value"
    echo "#"
    echo "# Generated by tools/predefined-macros/generate.sh on $(date -u +%Y-%m-%d)."
    echo "# C:   $3"
    echo "# C++: $4"
    echo "#"
    printf '%s\n' "$5" | sed 's/^/# /'
    echo "#"
  } >"$1"
}

# doc_header <file> <description> <c-source> <cpp-source> <source citation>
doc_header() {
  {
    echo "# Predefined macros of $2."
    echo "#"
    echo "# Format (as the EDG C/C++ front end's predefined_macros.txt):"
    echo "#   mode[,mode]   cannot_redefine   name   value"
    echo "#"
    echo "# Generated by tools/predefined-macros/generate.sh on $(date -u +%Y-%m-%d), from the"
    echo "# vendor's documentation: $5. The compiler cannot be run here, so the table lists its"
    echo "# documented macros, not a full -dM dump; a real installation defines more."
    echo "# C:   $3"
    echo "# C++: $4"
    echo "#"
  } >"$1"
}

gcc_table() { # gcc_table <name> <docker-platform>
  run="docker run --rm -i --platform $2 $GCC_IMAGE"
  $run gcc -x c -dM -E - </dev/null >"$TMP/c"
  $run g++ -x c++ -dM -E - </dev/null >"$TMP/cpp"
  version=$($run gcc --version | head -1)
  header "$OUT/$1.txt" "GCC on $2" "gcc -x c -dM -E -" "g++ -x c++ -dM -E -" "$version ($GCC_IMAGE)"
  merge "$TMP/c" "$TMP/cpp" gnu gcc gpp >>"$OUT/$1.txt"
}

clang_table() { # clang_table <name> <target>
  "$CLANG" --target="$2" -x c -dM -E - </dev/null >"$TMP/c"
  "$CLANG" --target="$2" -x c++ -dM -E - </dev/null >"$TMP/cpp"
  version=$("$CLANG" --version | head -1)
  header "$OUT/$1.txt" "Clang for $2" "clang --target=$2 -x c -dM -E -" \
    "clang --target=$2 -x c++ -dM -E -" "$version"
  merge "$TMP/c" "$TMP/cpp" clang clang_c clang_cpp >>"$OUT/$1.txt"
}

msvc_table() { # msvc_table <name> <target>
  opts="--target=$2 -fms-extensions -fms-compatibility -fms-compatibility-version=$MSVC_VERSION"
  # clang's own identity, which cl.exe does not predefine
  strip='^#define (__clang|__llvm__|__GNUC|__GXX|__VERSION__|__STDC_HOSTED__|__OBJC|__BLOCKS__)'
  "$CLANG" $opts -x c -dM -E - </dev/null | grep -Ev "$strip" >"$TMP/c"
  "$CLANG" $opts -x c++ -dM -E - </dev/null | grep -Ev "$strip" >"$TMP/cpp"
  version=$("$CLANG" --version | head -1)
  header "$OUT/$1.txt" "MSVC $MSVC_VERSION for $2, as clang predefines them in MSVC compatibility mode" \
    "clang $opts -x c -dM -E -" "clang $opts -x c++ -dM -E -" "$version"
  merge "$TMP/c" "$TMP/cpp" microsoft microsoft_c microsoft_cpp >>"$OUT/$1.txt"
}

clangcl_table() { # clangcl_table <name> <target>
  opts="--target=$2 -fms-extensions -fms-compatibility -fms-compatibility-version=$MSVC_VERSION"
  # unlike the MSVC tables, clang's identity macros stay: clang --driver-mode=cl predefines them
  "$CLANG" $opts -x c -dM -E - </dev/null >"$TMP/c"
  "$CLANG" $opts -x c++ -dM -E - </dev/null >"$TMP/cpp"
  version=$("$CLANG" --version | head -1)
  header "$OUT/$1.txt" "clang --driver-mode=cl (clang in MSVC mode) for $2" \
    "clang $opts -x c -dM -E -" "clang $opts -x c++ -dM -E -" "$version"
  merge "$TMP/c" "$TMP/cpp" microsoft microsoft_c microsoft_cpp >>"$OUT/$1.txt"
}

tcc_table() { # tcc_table <name> <docker-platform> <arch-description>
  run="docker run --rm -i --platform $2 $DEBIAN_IMAGE sh -c"
  $run "apt-get update -qq >/dev/null && apt-get install -y -qq tcc >/dev/null && \
    echo 'int x;' | tcc -E -dM - 2>/dev/null | sort" >"$TMP/c"
  $run "apt-get update -qq >/dev/null && apt-get install -y -qq tcc >/dev/null && \
    echo 'int x;' | tcc -xc++ -E -dM - 2>/dev/null | sort" >"$TMP/cpp"
  version=$($run "apt-get update -qq >/dev/null && apt-get install -y -qq tcc >/dev/null && \
    tcc --version" | head -1)
  header "$OUT/$1.txt" "TinyCC ($3)" "tcc -E -dM -" "tcc -xc++ -E -dM -" "$version ($DEBIAN_IMAGE)"
  merge "$TMP/c" "$TMP/cpp" tinycc tinycc_c tinycc_cpp >>"$OUT/$1.txt"
}

armgcc_table() { # armgcc_table <name> <cpu-options> <description>
  run="docker run --rm -i $DEBIAN_IMAGE sh -c"
  $run "apt-get update -qq >/dev/null && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    gcc-arm-none-eabi >/dev/null && echo 'int x;' | arm-none-eabi-gcc $2 -E -dM - 2>/dev/null | sort" >"$TMP/c"
  $run "apt-get update -qq >/dev/null && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    gcc-arm-none-eabi >/dev/null && echo 'int x;' | arm-none-eabi-g++ -x c++ $2 -E -dM - 2>/dev/null | sort" >"$TMP/cpp"
  version=$($run "apt-get update -qq >/dev/null && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    gcc-arm-none-eabi >/dev/null && arm-none-eabi-gcc --version" | head -1)
  header "$OUT/$1.txt" "$3" "arm-none-eabi-gcc $2 -x c -dM -E -" \
    "arm-none-eabi-g++ $2 -x c++ -dM -E -" "$version ($DEBIAN_IMAGE)"
  merge "$TMP/c" "$TMP/cpp" gnu gcc gpp >>"$OUT/$1.txt"
}

emcc_table() { # emcc_table <name>
  run="docker run --rm -i --platform linux/amd64 $EMSDK_IMAGE"
  $run sh -c "echo 'int x;' | emcc -x c -E -dM - 2>/dev/null | sort" >"$TMP/c"
  $run sh -c "echo 'int x;' | em++ -x c++ -E -dM - 2>/dev/null | sort" >"$TMP/cpp"
  version=$($run emcc --version | head -1)
  header "$OUT/$1.txt" "Emscripten for wasm32-unknown-emscripten" "emcc -x c -E -dM -" \
    "em++ -x c++ -E -dM -" "$version"
  merge "$TMP/c" "$TMP/cpp" clang clang_c clang_cpp >>"$OUT/$1.txt"
  cat >>"$OUT/$1.txt" <<'NOTES'
# The driver's own version macros, which emcc hands to clang as command-line definitions
# (Emscripten's documented predefined macros):
clang no  __EMSCRIPTEN_major__ 3
clang no  __EMSCRIPTEN_minor__ 1
clang no  __EMSCRIPTEN_tick__ 64
NOTES
}

nvcc_table() { # nvcc_table <name>
  run="docker run --rm -i $CUDA_IMAGE sh -c"
  # nvcc's own macros, as the CUDA Toolkit's nvcc predefines them for a .cu unit, read by
  # subtracting the host compiler's macros from what `nvcc -E -Xcompiler -dM` prints
  $run "echo 'int x;' > unit.cu && nvcc -E -Xcompiler -dM -x c++ unit.cu 2>/dev/null | grep '^#define' | sort" >"$TMP/nvcc"
  $run "gcc -x c++ -dM -E - </dev/null | sort" >"$TMP/host"
  version=$($run "nvcc --version" | tail -2 | head -1)
  {
    echo "# nvcc's own predefined macros (CUDA Toolkit), to merge over the host compiler's."
    echo "#"
    echo "# Format (as the EDG C/C++ front end's predefined_macros.txt):"
    echo "#   mode[,mode]   cannot_redefine   name   value"
    echo "#"
    echo "# Generated by tools/predefined-macros/generate.sh on $(date -u +%Y-%m-%d): the macros the"
    echo "# CUDA Toolkit's nvcc adds to the host compiler's set, read by subtracting"
    echo "# 'gcc -x c++ -dM -E -' from 'nvcc -E -Xcompiler -dM -x c++ unit.cu' in the CUDA image."
    echo "# $version ($CUDA_IMAGE)"
    echo "#"
    echo "# A unit nvcc compiles also has __CUDACC__ 1, which the CUDA Toolkit guide documents for"
    echo "# CUDA source files and the -E stage alone does not print; it is written by hand."
    echo "#"
    echo "all no  __CUDACC__ 1"
  } >"$OUT/$1.txt"
  comm -13 "$TMP/host" "$TMP/nvcc" | grep -Ev '__CUDA_ARCH|__NV_LEGACY' \
    | sed 's/^#define /all no  /' | LC_ALL=C sort -k3,3 -k1,1 >>"$OUT/$1.txt"
}

intel_table() { # intel_table <name> <target>
  "$CLANG" --target="$2" -x c -dM -E - </dev/null >"$TMP/c"
  "$CLANG" --target="$2" -x c++ -dM -E - </dev/null >"$TMP/cpp"
  version=$("$CLANG" --version | head -1)
  header "$OUT/$1.txt" \
    "Intel icx/icpx for $2, as clang predefines them, with Intel's own identifying macros" \
    "clang --target=$2 -x c -dM -E -" "clang --target=$2 -x c++ -dM -E -" \
    "$version; the Intel macros are the ones the compiler guide documents (oneAPI 2021.1)"
  merge "$TMP/c" "$TMP/cpp" clang clang_c clang_cpp >>"$OUT/$1.txt"
  # The LLVM-based Intel compilers predefine __INTEL_LLVM_COMPILER; the guide shows 202110 for
  # icx 2021.1 (Intel Developer Guide and Reference, "Use Predefined Macros to Specify Intel
  # Compilers"). An installed icx also predefines its full clang set around this value.
  echo "clang no  __INTEL_LLVM_COMPILER 202110" >>"$OUT/$1.txt"
}

armclang_table() { # armclang_table <name> <target>
  "$CLANG" --target="$2" -x c -dM -E - </dev/null >"$TMP/c"
  "$CLANG" --target="$2" -x c++ -dM -E - </dev/null >"$TMP/cpp"
  version=$("$CLANG" --version | head -1)
  header "$OUT/$1.txt" \
    "Arm Compiler for Embedded (armclang) for $2, as clang predefines it, with Arm's version macros" \
    "clang --target=$2 -x c -dM -E -" "clang --target=$2 -x c++ -dM -E -" \
    "$version; the Arm macros follow the armclang Reference Guide (Arm Compiler 6.19)"
  merge "$TMP/c" "$TMP/cpp" clang clang_c clang_cpp >>"$OUT/$1.txt"
  # Arm Compiler 6 defines the version as VVRRPPPP (6.19 -> 6190000); since 6.7 the same value
  # rides under __ARMCOMPILER_VERSION (armclang Reference Guide, "Predefined macros").
  echo "clang no  __ARMCC_VERSION 6190000" >>"$OUT/$1.txt"
  echo "clang no  __ARMCOMPILER_VERSION 6190000" >>"$OUT/$1.txt"
}

iccarm_table() { # iccarm_table <name>
  doc_header "$OUT/$1.txt" \
    "IAR iccarm (IAR C/C++ Compiler for Arm)" \
    "not documented by the vendor" "not documented by the vendor" \
    "the IAR C/C++ Development Guide for Arm, chapter \"Predefined symbols\""
  cat >>"$OUT/$1.txt" <<'ROWS'
# The identity macros IAR's guide documents: __VER__ encodes the version as VVRRPPPP
# (9.40 -> 9400000), the way CMSIS' headers read it.
iar no  __BUILD_NUMBER__ 1
iar no  __IAR_SYSTEMS_ICC__ 9
iar no  __ICCARM__ 1
iar no  __VER__ 9400000
ROWS
}

ti_arm_table() { # ti_arm_table <name>
  doc_header "$OUT/$1.txt" \
    "TI armcl (TI ARM C/C++ Optimizing Compiler)" \
    "not documented by the vendor" "not documented by the vendor" \
    "the TI ARM Optimizing C/C++ Compiler User's Guide (SPRU186), chapter \"Predefined Symbol Names\""
  cat >>"$OUT/$1.txt" <<'ROWS'
# __TI_COMPILER_VERSION__ encodes the version as VVRRPPPPP (21.6.0 -> 21060000); __TI_ARM__ is
# defined for Arm targets and distinguishes armcl from cl430, which defines __MSP430__.
ti_arm no  __TI_ARM__ 1
ti_arm no  __TI_COMPILER_VERSION__ 21060000
ROWS
}

ti_msp430_table() { # ti_msp430_table <name>
  doc_header "$OUT/$1.txt" \
    "TI cl430 (TI MSP430 C/C++ Optimizing Compiler)" \
    "not documented by the vendor" "not documented by the vendor" \
    "the TI MSP430 Optimizing C/C++ Compiler User's Guide (SLAU132), chapter \"Predefined Symbol Names\""
  cat >>"$OUT/$1.txt" <<'ROWS'
# __TI_COMPILER_VERSION__ encodes the version as VVRRPPPPP; __MSP430__ marks the target.
ti_msp430 no  __MSP430__ 1
ti_msp430 no  __TI_COMPILER_VERSION__ 21060000
ROWS
}

TABLES="$@"

want() { # want <table>: true when no table names were given, or <table> is one of them
  [ -z "$TABLES" ] && return 0
  for asked in $TABLES; do [ "$asked" = "$1" ] && return 0; done
  return 1
}

if want gcc-linux-x86_64; then gcc_table gcc-linux-x86_64 linux/amd64; fi
if want gcc-linux-aarch64; then gcc_table gcc-linux-aarch64 linux/arm64; fi
if want clang-linux-x86_64; then clang_table clang-linux-x86_64 x86_64-unknown-linux-gnu; fi
if want clang-linux-aarch64; then clang_table clang-linux-aarch64 aarch64-unknown-linux-gnu; fi
if want clang-macos-arm64; then clang_table clang-macos-arm64 arm64-apple-macosx; fi
if want clang-macos-x86_64; then clang_table clang-macos-x86_64 x86_64-apple-macosx; fi
if want msvc-windows-x64; then msvc_table msvc-windows-x64 x86_64-pc-windows-msvc; fi
