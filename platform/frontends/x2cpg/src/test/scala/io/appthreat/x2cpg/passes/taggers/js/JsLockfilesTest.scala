package io.appthreat.x2cpg.passes.taggers.js

import org.scalatest.matchers.should.Matchers
import org.scalatest.wordspec.AnyWordSpec

/** The lockfile version readers. Every fixture is a trimmed excerpt of a real lockfile: yarn v1
  * from node-express-boilerplate (179ae84), yarn berry from yarnpkg/berry, pnpm v6 from
  * prawito/express-prisma, pnpm v9 from SertacN/express-drizzle-starter (00a5362e), bun.lock from
  * oven-sh/bun.
  */
class JsLockfilesTest extends AnyWordSpec with Matchers:

  private def versionsOf(fileName: String, content: String): Seq[(String, String)] =
      JsLockfiles.resolutionsOf(fileName, content).map(r => r.name -> r.version)

  "the npm lockfile reader" should {
      "read the version of each top-level package" in {
          val content =
              """{
                |  "lockfileVersion": 3,
                |  "packages": {
                |    "": { "name": "p" },
                |    "node_modules/express": { "version": "4.18.2" },
                |    "node_modules/node-fetch": { "version": "2.6.7" }
                |  }
                |}""".stripMargin
          versionsOf("package-lock.json", content) should contain theSameElementsAs
              Seq("express" -> "4.18.2", "node-fetch" -> "2.6.7")
      }
  }

  "the yarn v1 lockfile reader" should {
      val content =
          """# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
            |# yarn lockfile v1
            |
            |
            |"@types/express-serve-static-core@*":
            |  version "4.17.33"
            |  resolved "https://registry.yarnpkg.com/@types/express-serve-static-core/-/express-serve-static-core-4.17.33.tgz#f343d5e0a08f134cce9f30343dfd1c81d61419e9"
            |
            |express@^4.17.1, express@^4.17.0:
            |  version "4.17.1"
            |  resolved "https://registry.yarnpkg.com/express/-/express-4.17.1.tgz"
            |  dependencies:
            |    accepts "~1.3.7"
            |
            |mongoose@^5.7.7:
            |  version "5.13.20"
            |  resolved "https://registry.yarnpkg.com/mongoose/-/mongoose-5.13.20.tgz"
            |""".stripMargin
      "read the version each block resolved, one block serving several ranges" in {
          // both ranges name the same resolution, so the pair appears once per range
          versionsOf("yarn.lock", content).distinct should contain theSameElementsAs Seq(
            "@types/express-serve-static-core" -> "4.17.33",
            "express"                          -> "4.17.1",
            "mongoose"                         -> "5.13.20"
          )
      }
      "keep both resolutions of a name that resolved apart (no guess)" in {
          val apart = content + """
                                  |express@^4.18.0:
                                  |  version "4.18.2"
                                  |""".stripMargin
          versionsOf("yarn.lock", apart).distinct should contain theSameElementsAs Seq(
            "@types/express-serve-static-core" -> "4.17.33",
            "mongoose"                         -> "5.13.20",
            "express"                          -> "4.17.1",
            "express"                          -> "4.18.2"
          )
      }
  }

  "the yarn berry lockfile reader" should {
      val content =
          """# This file is generated by running "yarn install" inside your project.
            |
            |__metadata:
            |  version: 10
            |  cacheKey: 10
            |
            |"@actions/core@npm:^1.2.6":
            |  version: 1.2.6
            |  resolution: "@actions/core@npm:1.2.6"
            |  languageName: node
            |  linkType: hard
            |
            |"@scope/tools@workspace:packages/tools":
            |  version: 0.0.0-use.local
            |  resolution: "@scope/tools@workspace:packages/tools"
            |  languageName: unknown
            |  linkType: soft
            |""".stripMargin
      "read registry resolutions and skip workspace keys" in {
          versionsOf("yarn.lock", content) shouldBe Seq("@actions/core" -> "1.2.6")
      }
  }

  "the pnpm v6 lockfile reader" should {
      val content =
          """lockfileVersion: '6.0'
            |
            |dependencies:
            |  '@prisma/client':
            |    specifier: 5.2.0
            |    version: 5.2.0(prisma@5.2.0)
            |  express:
            |    specifier: ^4.18.2
            |    version: 4.18.2
            |
            |devDependencies:
            |  '@types/express':
            |    specifier: ^4.17.17
            |    version: 4.17.17
            |
            |packages:
            |  /express/4.18.2:
            |    resolution: {integrity: sha512-...}
            |""".stripMargin
      "read the top-level sections, peers stripped, not the hoisted packages" in {
          versionsOf("pnpm-lock.yaml", content) should contain theSameElementsAs Seq(
            "@prisma/client" -> "5.2.0",
            "express"        -> "4.18.2",
            "@types/express" -> "4.17.17"
          )
      }
  }

  "the pnpm v9 lockfile reader" should {
      val content =
          """lockfileVersion: '9.0'
            |
            |importers:
            |
            |  .:
            |    devDependencies:
            |      prettier:
            |        specifier: ^3.9.9
            |        version: 3.9.9
            |
            |  apps/api:
            |    dependencies:
            |      drizzle-orm:
            |        specifier: ^0.45.3
            |        version: 0.45.3(@types/pg@8.23.1)(pg@8.23.1)
            |      express:
            |        specifier: ^5.2.1
            |        version: 5.2.1
            |
            |packages:
            |  express@5.2.1:
            |    resolution: {integrity: sha512-...}
            |""".stripMargin
      "read what each importer resolved, not the hoisted packages" in {
          versionsOf("pnpm-lock.yaml", content) should contain theSameElementsAs Seq(
            "prettier"    -> "3.9.9",
            "drizzle-orm" -> "0.45.3",
            "express"     -> "5.2.1"
          )
      }
      "keep both resolutions when two workspaces pinned a package apart" in {
          val apart =
              """lockfileVersion: '9.0'
                |
                |importers:
                |
                |  .:
                |    devDependencies:
                |      prettier:
                |        specifier: ^3.9.9
                |        version: 3.9.9
                |
                |  apps/api:
                |    devDependencies:
                |      prettier:
                |        specifier: ^3.4.0
                |        version: 3.4.2
                |""".stripMargin
          val found = versionsOf("pnpm-lock.yaml", apart)
          found.count(_._1 == "prettier") shouldBe 2
          (found should contain).allOf("prettier" -> "3.9.9", "prettier" -> "3.4.2")
      }
  }

  "the bun lockfile reader" should {
      val content =
          """{
            |  "lockfileVersion": 1,
            |  "configVersion": 1,
            |  "workspaces": {
            |    "": {
            |      "name": "bun",
            |      "devDependencies": {
            |        "@lezer/common": "1.5.2",
            |        "react": "18.3.1",
            |      },
            |    },
            |    "packages/bun-types": {
            |      "name": "bun-types",
            |      "dependencies": {
            |        "@types/node": "*",
            |        "undici-types": "8.3.0",
            |      },
            |    },
            |  },
            |  // the hoisted copies, then a nested one keyed by its path
            |  "packages": {
            |    "@babel/core/semver": ["semver@6.3.1", "", {}, "sha512-..."],
            |    "@lezer/common": ["@lezer/common@1.5.2", "", {"peerDependencies": {}}, "sha512-..."],
            |    "react": ["react@18.3.1", "", {"peerDependencies": {}}, "sha512-..."],
            |    "undici-types": ["undici-types@8.3.0", "", {}, "sha512-..."]
            |  }
            |}""".stripMargin
      "read the hoisted version of every package, comments and trailing commas tolerated" in {
          versionsOf("bun.lock", content) should contain theSameElementsAs Seq(
            "@lezer/common" -> "1.5.2",
            "react"         -> "18.3.1",
            "undici-types"  -> "8.3.0"
          )
      }
  }
  "the readers" should {
      "report a v2 npm lockfile's packages and dependencies sections, which agree" in {
          val content =
              """{
                |  "lockfileVersion": 2,
                |  "packages": {
                |    "": { "name": "p" },
                |    "node_modules/express": { "version": "4.18.2" },
                |    "node_modules/express/node_modules/debug": { "version": "2.6.9" }
                |  },
                |  "dependencies": {
                |    "express": { "version": "4.18.2" }
                |  }
                |}""".stripMargin
          versionsOf("package-lock.json", content) shouldBe Seq(
            "express" -> "4.18.2",
            "express" -> "4.18.2"
          )
      }
      "give each yarn key its range, berry's protocol stripped" in {
          val content =
              """__metadata:
                |  version: 8
                |
                |"debug@npm:^4.1.0, debug@npm:^4.3.4":
                |  version: 4.3.4
                |  dependencies:
                |    ms: "npm:2.1.2"
                |""".stripMargin
          JsLockfiles.resolutionsOf("yarn.lock", content) should contain theSameElementsAs Seq(
            Resolution("debug", Some("^4.1.0"), "4.3.4"),
            Resolution("debug", Some("^4.3.4"), "4.3.4")
          )
      }
      "not take a yarn block's dependency named version... for the block's version" in {
          val content =
              """semver-tools@^1.0.0:
                |  dependencies:
                |    versions "2.0.0"
                |  version "1.0.1"
                |""".stripMargin
          versionsOf("yarn.lock", content) shouldBe Seq("semver-tools" -> "1.0.1")
      }
      "skip a yarn alias, whose resolution is another package's" in {
          val content =
              """"string-width-cjs@npm:string-width@^4.2.0":
                |  version "4.2.3"
                |
                |"@scope/a@^1.0.0":
                |  version "1.0.0"
                |""".stripMargin
          versionsOf("yarn.lock", content) shouldBe Seq("@scope/a" -> "1.0.0")
      }
      "read pnpm v6/v9 specifiers as the ranges the versions served" in {
          val content =
              """lockfileVersion: '9.0'
                |
                |importers:
                |
                |  .:
                |    dependencies:
                |      express:
                |        specifier: ^4.17.0
                |        version: 4.18.2
                |""".stripMargin
          JsLockfiles.resolutionsOf("pnpm-lock.yaml", content) shouldBe Seq(
            Resolution("express", Some("^4.17.0"), "4.18.2")
          )
      }
      "read pnpm v5's inline versions, peers stripped, and not its specifiers" in {
          val content =
              """lockfileVersion: 5.4
                |
                |importers:
                |
                |  .:
                |    specifiers:
                |      '@prisma/client': ^4.0.0
                |      express: ^4.18.2
                |    dependencies:
                |      '@prisma/client': 4.16.2_prisma@4.16.2
                |      express: 4.18.2
                |      local-lib: link:../lib
                |
                |packages:
                |
                |  /express/4.18.2:
                |    resolution: {integrity: sha512-...}
                |""".stripMargin
          versionsOf("pnpm-lock.yaml", content) should contain theSameElementsAs Seq(
            "@prisma/client" -> "4.16.2",
            "express"        -> "4.18.2"
          )
      }
  }
end JsLockfilesTest
